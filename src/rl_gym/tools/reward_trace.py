"""Per-epoch reward trace: a scripted greedy episode, every reward event labelled (P2.0b).

Writes `docs/RL_GYM_REWARD_TRACE.md`. The point is to check that §6.4's classification ladder
puts the right label on each individual event, which the episode-level counts cannot show --
118 declines could be the correct total with several of them individually misclassified.

Reported: the first 40 steps and every step carrying three or more events; for each, the step's
reward and the events composing it, each with its kind, rid and amount, and for pickups the
realized wait. Any step whose listed amounts do not sum to the step's reward is called out, and
so is the sum over all steps against `episode_summary()["episode_reward"]`.

Runs with the reference scenario and `base_seed` absent, so `G_RANDOM_SEED` stays at the row's
42 (D7) and the trace describes the same sample path as `docs/baseline_user_stats.csv`.

    python -m src.rl_gym.tools.reward_trace [--output]

`--output` keeps `skip_output = False` so a `1_user-stats.csv` is written for cross-checking;
the default suppresses it, since the trace itself is the deliverable.
"""

import argparse
import os
import sys
import time

import numpy as np

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "..")))

from src.misc.globals import G_SIM_END_TIME  # noqa: E402
from src.rl_gym.gym_env import SDPDPAssignmentEnv  # noqa: E402
from src.rl_gym.policies import greedy_action  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
SCS = os.path.join(ROOT, "studies", "example_study", "scenarios")
REPORT = os.path.join(ROOT, "docs", "RL_GYM_REWARD_TRACE.md")
K = 8
HEAD_STEPS = 40          # the first N steps are always listed
BUSY_EVENTS = 3          # and any step with at least this many events
TOL = 1e-9               # float tolerance for the per-step sum check


def run_trace(skip_output=True):
    """One scripted greedy episode with `track_events` on, returning every step's events."""
    env = SDPDPAssignmentEnv({
        "constant_cfg_path": os.path.join(SCS, "constant_config_depot_cali_sc_1.csv"),
        "scenario_cfg_path": os.path.join(SCS, "example_depot_cali_sc_1.csv"),
        "K": K,
        "skip_output": skip_output,
        "track_events": True,
        "env_id": 0,
        # base_seed absent on purpose: keep G_RANDOM_SEED at the row's 42 (D7)
    })
    end_time = float(env.scenario_parameters[G_SIM_END_TIME])

    steps = []               # one dict per gym step
    obs, info = env.reset()
    sim_time = float(info["sim_time"])

    t0 = time.perf_counter()
    terminated = False
    while not terminated:
        action = greedy_action(obs, env.action_masks(), env.observation_layout)
        obs, reward, terminated, truncated, info = env.step(action)
        assert not truncated, "episode must end terminated, not truncated (D6)"
        steps.append({
            "n": len(steps) + 1,
            "sim_time": sim_time,
            "action": int(action),
            "reward": float(reward),
            "events": list(info.get("reward_events", [])),
            "terminal": bool(terminated),
        })
        if not terminated:
            sim_time = float(info["sim_time"])
    wall = time.perf_counter() - t0

    summary = info["episode_summary"]
    env.close()
    return steps, summary, end_time, wall


def format_report(steps, summary, end_time, wall):
    event_total = sum(e[2] for s in steps for e in s["events"])
    mismatched = [s for s in steps
                  if abs(sum(e[2] for e in s["events"]) - s["reward"]) > TOL]
    listed = [s for s in steps
              if s["n"] <= HEAD_STEPS or len(s["events"]) >= BUSY_EVENTS or s["terminal"]]
    kinds = {}
    for s in steps:
        for kind, _rid, amount, _detail in s["events"]:
            entry = kinds.setdefault(kind, {"n": 0, "total": 0.0})
            entry["n"] += 1
            entry["total"] += amount

    L = []
    L.append("# RL Gym — per-epoch reward trace (P2.0b)\n")
    L.append("Generated by `src/rl_gym/tools/reward_trace.py`. Scripted greedy through the Gym "
             "API on the\nreference scenario, `base_seed` absent so `G_RANDOM_SEED` is the "
             "row's 42 (D7).\n")
    L.append(f"- gym steps: **{len(steps)}**")
    L.append(f"- reward events: **{sum(len(s['events']) for s in steps)}**")
    L.append(f"- episode wall clock: {wall:.2f} s ({len(steps) / wall:.2f} steps/s)")
    L.append("")

    L.append("## Reconciliation\n")
    L.append("| check | value |")
    L.append("|---|---|")
    L.append(f"| Σ event amounts, all steps | {event_total:.6f} |")
    L.append(f"| `episode_summary()['episode_reward']` | {summary['episode_reward']:.6f} |")
    L.append(f"| difference | {event_total - summary['episode_reward']:.2e} |")
    L.append(f"| Σ step rewards | {sum(s['reward'] for s in steps):.6f} |")
    L.append(f"| `unflushed_reward` | {summary['unflushed_reward']} |")
    L.append(f"| steps whose events do not sum to the step reward | **{len(mismatched)}** |")
    L.append("")
    if mismatched:
        L.append("**Steps that do not reconcile — every one is a defect:**\n")
        for s in mismatched:
            L.append(f"- step {s['n']} (t={s['sim_time']:.0f}): reward {s['reward']:.6f} "
                     f"vs Σ events {sum(e[2] for e in s['events']):.6f}")
        L.append("")
    else:
        L.append("Every step's listed amounts sum to that step's reward, within "
                 f"{TOL:g}.\n")

    L.append("## Horizon margin\n")
    margin = summary.get("horizon_margin")
    L.append(f"- `last_dropoff`: {summary.get('last_dropoff')}")
    L.append(f"- `end_time`: {end_time:.0f}")
    L.append(f"- `horizon_margin`: {'n/a' if margin is None else f'{margin:.1f} s'} "
             "— negative would mean the post-`end_time` tail did work (§6.4, P2.13)")
    L.append("")

    L.append("## Events by kind\n")
    L.append("| kind | events | Σ amount |")
    L.append("|---|---|---|")
    for kind in sorted(kinds, key=lambda k: -kinds[k]["n"]):
        L.append(f"| `{kind}` | {kinds[kind]['n']} | {kinds[kind]['total']:.6f} |")
    L.append("")
    L.append("Counts here are events, not distinct rids: a rider whose `record_boarding` fires "
             "twice\ncontributes two `pickup` events whose amounts sum to one pickup at the "
             "final `pu_time`\n(§6.4, last-write-wins).\n")

    # A repeated `record_boarding` can straddle the step selection below, leaving one of its two
    # events listed and the other not -- a lone negative pickup reads like a defect when it is
    # the §6.4 re-price. List both halves of every such pair explicitly.
    pickups_by_rid = {}
    for s in steps:
        for kind, rid, amount, detail in s["events"]:
            if kind == "pickup":
                pickups_by_rid.setdefault(rid, []).append((s["n"], amount, detail))
    repeats = {rid: evs for rid, evs in pickups_by_rid.items() if len(evs) > 1}
    L.append("## Riders whose `record_boarding` fired more than once\n")
    if not repeats:
        L.append("None on this day.\n")
    else:
        L.append("Last-write-wins (§6.4): the first event prices a stale `pu_time`, the repeat "
                 "charges the\ndelta, and the two sum to one pickup at the final `pu_time` -- "
                 "the value the output file\nrecords. Both halves are listed here because the "
                 "step selection below may show only one.\n")
        L.append("| rid | events (step, amount, wait) | Σ amount | net wait |")
        L.append("|---|---|---|---|")
        for rid in sorted(repeats, key=lambda r: str(r)):
            evs = repeats[rid]
            cell = "<br>".join(
                f"step {n}: {a:+.6f}" + ("" if d is None else f", wait {d:.1f} s")
                for n, a, d in evs)
            L.append(f"| {rid} | {cell} | {sum(a for _n, a, _d in evs):+.6f} | "
                     f"{evs[-1][2]:.1f} s |")
        L.append("")

    L.append("## Episode summary\n")
    L.append("| field | value |")
    L.append("|---|---|")
    for key in sorted(summary):
        L.append(f"| {key} | {summary[key]} |")
    L.append("")

    L.append(f"## Step detail\n")
    L.append(f"The first {HEAD_STEPS} steps, every step with {BUSY_EVENTS} or more events, and "
             "the terminal step.\n")
    L.append("| step | sim_time | action | reward | events |")
    L.append("|---|---|---|---|---|")
    for s in listed:
        if s["events"]:
            parts = []
            for kind, rid, amount, detail in s["events"]:
                wait = "" if detail is None else f", wait {detail:.1f} s"
                parts.append(f"`{kind}` rid {rid} {amount:+.6f}{wait}")
            cell = "<br>".join(parts)
        else:
            cell = "—"
        label = f"{s['n']}{' (terminal)' if s['terminal'] else ''}"
        L.append(f"| {label} | {s['sim_time']:.0f} | {s['action']} | "
                 f"{s['reward']:+.6f} | {cell} |")
    L.append("")
    return "\n".join(L), mismatched, event_total


def main():
    ap = argparse.ArgumentParser(description="Per-epoch reward trace (P2.0b)")
    ap.add_argument("--output", action="store_true",
                    help="write the simulation's own output files as well")
    args = ap.parse_args()

    print(f"numpy {np.__version__} | scripted greedy, track_events=True")
    steps, summary, end_time, wall = run_trace(skip_output=not args.output)
    text, mismatched, event_total = format_report(steps, summary, end_time, wall)
    with open(REPORT, "w") as fh:
        fh.write(text)

    print(f"steps {len(steps)} | events {sum(len(s['events']) for s in steps)} | "
          f"wall {wall:.2f} s")
    print(f"Σ events {event_total:.6f} vs episode_reward {summary['episode_reward']:.6f} "
          f"(diff {event_total - summary['episode_reward']:.2e})")
    print(f"steps not reconciling: {len(mismatched)}")
    print(f"horizon_margin {summary.get('horizon_margin')} | "
          f"last_dropoff {summary.get('last_dropoff')}")
    print(f"unclassified {summary.get('unclassified')} | wrote {REPORT}")
    return 1 if mismatched else 0


if __name__ == "__main__":
    sys.exit(main())
